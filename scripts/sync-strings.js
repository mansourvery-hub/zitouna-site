/* ------------------------------------------------------------------ manifest */

const manifest = {
  _comment:
    'GENERATED by scripts/sync-strings.js from the Zitouna app repo. Do not edit by hand.\n' +
    'Asserted against the running demo by tests/e2e/app-parity.spec.js.',
  tabs,
  stages,
  buckets,
  copy,
};

const json = JSON.stringify(manifest, null, 2) + '\n';

/** Writes `content` only when it differs; in --check mode records staleness instead. */
function put(destRel, content) {
  const dest = path.join(SITE, destRel);
  const existed = fs.existsSync(dest);
  const same = existed && fs.readFileSync(dest, 'utf8') === content;
  if (same) {
    log(`  = ${destRel} (up to date)`);
    return;
  }
  if (CHECK) {
    stale.push(destRel);
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
  log(`  ${existed ? '~' : '+'} ${destRel}`);
}

const stale = [];

put(OUT, json);

/* The same manifest, emitted as a script rather than fetched as JSON: the demo needs it
 * synchronously, before it paints its first tab, and a fetch would mean the page renders the
 * wrong strings and then corrects itself. */
put(
  'src/app-ui.js',
  `${BANNER}window.ZITOUNA_UI = ${JSON.stringify(
    { tabs, stages, buckets, copy },
    null,
    2
  )};\n`
);

if (CHECK && stale.length) {
  console.error(
    `\n[sync-strings] ${stale.length} generated file(s) out of date:\n` +
      stale.map((f) => `  - ${f}`).join('\n') +
      `\n\nRun \`node scripts/sync-strings.js\` and commit the result, then reconcile the demo\n` +
      `against it — tests/e2e/app-parity.spec.js will tell you what moved.\n`
  );
  process.exit(1);
}

log('\n[sync-strings] up to date.');
