#!/usr/bin/env node
/**
 * scripts/sync-strings.js
 *
 * `sync-design.js` keeps the demo's *tokens and fonts* honest. It says nothing about the demo's
 * *copy* — which strings it shows, in what order, on which tabs. Those are hand-written in
 * `demo.js`, so an app change to them drifts the demo silently.
 *
 * That is not hypothetical. Renaming `Check Ripeness` in `app_en.arb`, or reordering the parcel
 * screen's tabs, leaves `sync-design --check`, the unit suite and the whole e2e suite green while
 * the demo goes on serving the old string. Nothing in the repository compared the two.
 *
 * This closes that gap. It reads the app's Dart and ARB and writes `design/app-ui.json` — a
 * manifest of tab order, stage names, bucket names and the copy the demo renders. It is generated,
 * committed, and `--check`-able. `tests/e2e/app-parity.spec.js` then renders the real demo and
 * compares that manifest against what the browser actually shows.
 *
 * Between them the two halves catch the two different failures:
 *   manifest stale            -> `--check` fails: the app changed and nobody re-derived it
 *   manifest fresh, demo drift -> the spec fails: the demo no longer matches the app
 *
 * Every pattern here fails loudly rather than degrading. A Dart refactor that moves a literal
 * somewhere this cannot see is exactly the drift worth catching, and a quiet empty section would
 * report "no drift" instead.
 *
 *   node scripts/sync-strings.js           # verify + write
 *   node scripts/sync-strings.js --check   # fail if the manifest is stale
 */
import fs from 'node:fs';
import path from 'node:path';

const APP_DIR = process.env.ZITOUNA_APP_DIR || '/home/mohamed/Desktop/Github/Zitouna';
const SITE = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const CHECK = process.argv.includes('--check');
const OUT = 'design/app-ui.json';

const read = (rel) => fs.readFileSync(path.join(APP_DIR, rel), 'utf8');
const log = (m) => process.stdout.write(m + '\n');

const BANNER =
  `/* GENERATED by scripts/sync-strings.js from the Zitouna app repo.\n` +
  `   Do not edit by hand — run \`node scripts/sync-strings.js\`. */\n`;

if (!fs.existsSync(APP_DIR)) {
  console.error(
    `[sync-strings] App repo not found at ${APP_DIR}.\n` +
    `                Set ZITOUNA_APP_DIR to the Zitouna checkout, or clone it alongside this repo.`
  );
  process.exit(1);
}

/**
 * One ARB value, or a hard failure. ARB is JSON with `@key` metadata blocks interleaved, so the
 * value is read by parsing rather than by regex — a regex here would also match the key inside a
 * placeholder spec and quietly return the wrong string.
 */
const arb = JSON.parse(read('lib/l10n/app_en.arb'));
const need = (key, why) => {
  const v = arb[key];
  if (typeof v !== 'string') {
    throw new Error(`app_en.arb: no string for "${key}" (${why})`);
  }
  return v;
};

/* ------------------------------------------------------------------ tabs */

/* The parcel screen's tab bar, read from the widget that builds it rather than from the ARB alone:
 * the ARB has all five strings, but only the screen knows that these five are the tabs and that
 * this is their order. Taking the list from the ARB would let a string that is not a tab — a
 * screen title, an error — be mistaken for one. */
log('[sync-strings] parcel tabs');
const SCREEN_FILE = 'lib/screens/parcel_detail_screen.dart';
const screenSrc = read(SCREEN_FILE);

const tabBlock = screenSrc.match(/l10n\.(tabOverview)([\s\S]*?)l10n\.tabYears,/);
if (!tabBlock) throw new Error(`${SCREEN_FILE}: could not find the tab label list`);
const tabOrder = ['tabOverview', 'tabRipeness', 'tabHarvest', 'tabMill', 'tabYears'].filter(
  (k) => tabBlock[0].includes(`l10n.${k}`)
);
if (tabOrder.length !== 5) {
  throw new Error(`${SCREEN_FILE}: expected 5 parcel tabs, found ${tabOrder.length}: ${tabOrder}`);
}
const tabs = tabOrder.map((key) => ({ key, label: need(key, `parcel tab ${key}`) }));

/* ------------------------------------------------------------------ stages and buckets */

log('[sync-strings] ripeness stages');
/* The four stages, in the app's enum order. `RipenessGauge` is declared in enums.dart, so the
 * order comes from there: the ARB alone cannot say which stage is which index. */
const enumsSrc = read('lib/data/models/enums.dart');
const gaugeEnum = enumsSrc.match(/enum RipenessGauge\s*\{([\s\S]*?)\}/);
if (!gaugeEnum) throw new Error('enums.dart: no `enum RipenessGauge`');
const stageOrder = gaugeEnum[1]
  .split(',')
  .map((s) => s.trim())
  .filter((s) => /^[a-zA-Z]/.test(s));
if (stageOrder.length !== 4) {
  throw new Error(`enums.dart: expected 4 RipenessGauge values, found ${stageOrder.length}`);
}
const STAGE_KEY = { tooEarly: 'stageTooEarly', soon: 'stageSoon', pickNow: 'stagePickNow', gettingLate: 'stageGettingLate' };
const stages = stageOrder.map((name) => {
  const key = STAGE_KEY[name];
  if (!key) throw new Error(`enums.dart: unmapped RipeningGauge value "${name}" — add it to STAGE_KEY`);
  return { name, key, label: need(key, `stage ${name}`) };
});

log('[sync-strings] ripeness buckets');
const BUCKET_KEY = { green: 'bucketGreen', turning: 'bucketTurning', purple: 'bucketPurple', black: 'bucketBlack' };
const buckets = Object.entries(BUCKET_KEY).map(([name, key]) => ({
  name,
  key,
  label: need(key, `bucket ${name}`),
}));

